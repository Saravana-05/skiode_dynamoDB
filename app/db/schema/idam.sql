-- IDAM schema: the user table used by RBAC / user management.
-- One row per user = the old auth_user row + its form_generator_userdata row
-- (the User and UserData objects in app/domain/user_domain.py).
-- All statements are idempotent; run with:  python -m app.idam.init_idam

CREATE SCHEMA IF NOT EXISTS idam;

CREATE TABLE IF NOT EXISTS idam."user" (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR NOT NULL UNIQUE,
    email               VARCHAR NOT NULL,
    password            VARCHAR NOT NULL DEFAULT '!',
    is_superuser        BOOLEAN NOT NULL DEFAULT FALSE,
    is_staff            BOOLEAN NOT NULL DEFAULT FALSE,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    date_joined         TIMESTAMP NOT NULL DEFAULT NOW(),
    user_name           VARCHAR,
    profile_pic         VARCHAR,
    user_profile_schema VARCHAR,
    is_lead             BOOLEAN NOT NULL DEFAULT FALSE,
    organization_id     BIGINT,
    usergroup_id        BIGINT,
    ref_id              VARCHAR,
    created_at          TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_idam_user_email ON idam."user" (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_idam_user_org ON idam."user" (organization_id);