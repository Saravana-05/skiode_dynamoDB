"""
Per-project user table, named after the project.

Every project gets its own table, created (empty) when the project is created:

    project "testing"          -> idam."testing_user"
    project "Bank Management"  -> idam."bank_management_user"

(name lower-cased, non-alphanumerics -> "_"; if that name is already taken by
another project's table it becomes "<name>_<project_id>_user"; a name with no
usable characters falls back to "project_<project_id>_user".)

Because a project can be renamed, the project -> table mapping is stored in
idam.project_user_table instead of being re-derived from the name. Renaming a
project renames its table too (rename_table); deleting it drops the table.

Columns of the project user table:
    id        identity PK
    user_id   -> idam."user"(id)   (UNIQUE: a user appears once per project)
    added_by  who added them (token user_id, optional)
    created_at

Entering a user into that table is what links them to RBAC. In ONE transaction
add_user() also:
  1. writes idam.user_project          -> membership; user_has_permission()
                                          rejects non-members of a project
  2. writes rbac_user_roles rows with project_id = <this project>
                                          -> roles that count only in this project

remove_user() undoes all three.

Prerequisites (run once): python -m app.db.init_rbac ; python -m app.idam.init_idam
"""
import re

from ....core.database import ensure_pool, execute, fetch, fetchrow

_REGISTRY = "idam.project_user_table"


def _slug(name: str | None) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", (name or "").lower()).strip("_")
    return s[:40].strip("_")


def _q(table_name: str) -> str:
    # table_name only ever contains [a-z0-9_] (built by _pick_name), so quoting is safe.
    return f'idam."{table_name}"'


async def _ensure_registry() -> None:
    await execute("CREATE SCHEMA IF NOT EXISTS idam")
    await execute(
        f"""
        CREATE TABLE IF NOT EXISTS {_REGISTRY} (
            project_id INTEGER PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
            table_name VARCHAR NOT NULL UNIQUE
        )
        """
    )


async def _exists(table_name: str) -> bool:
    row = await fetchrow("SELECT to_regclass($1) AS t", _q(table_name))
    return row["t"] is not None


async def _pick_name(project_id: int, project_name: str | None) -> str:
    """A free table name for this project (never clashes with another table)."""
    slug = _slug(project_name)
    if not slug:
        candidates = [f"project_{project_id}_user"]
    else:
        candidates = [f"{slug}_user", f"{slug}_{project_id}_user"]
    for name in candidates:
        if not await _exists(name):
            return name
    return f"project_{project_id}_user"


async def table_name_of(project_id) -> str | None:
    """Registered table name of a project, or None."""
    await _ensure_registry()
    row = await fetchrow(f"SELECT table_name FROM {_REGISTRY} WHERE project_id = $1", int(project_id))
    return row["table_name"] if row else None


async def ensure_table(project_id) -> str:
    """Create the project's user table if needed (idempotent). Returns its name."""
    pid = int(project_id)
    await _ensure_registry()
    existing = await table_name_of(pid)
    if existing and await _exists(existing):
        return existing

    proj = await fetchrow("SELECT name FROM projects WHERE id = $1", pid)
    if not proj:
        raise ValueError(f"Project {pid} does not exist")

    # Tables made by the first version of this feature were called
    # project_<id>_user - adopt them (renamed) instead of creating a second one.
    legacy = f"project_{pid}_user"
    name = existing or await _pick_name(pid, proj["name"])
    if not existing and await _exists(legacy):
        if legacy != name:
            await execute(f"ALTER TABLE {_q(legacy)} RENAME TO \"{name}\"")
        else:
            name = legacy
    else:
        await execute(
            f"""
            CREATE TABLE IF NOT EXISTS {_q(name)} (
                id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id    BIGINT NOT NULL UNIQUE REFERENCES idam."user"(id) ON DELETE CASCADE,
                added_by   VARCHAR,
                created_at TIMESTAMP NOT NULL DEFAULT NOW()
            )
            """
        )
    await execute(
        f"INSERT INTO {_REGISTRY} (project_id, table_name) VALUES ($1, $2) "
        f"ON CONFLICT (project_id) DO UPDATE SET table_name = EXCLUDED.table_name",
        pid, name,
    )
    return name


async def rename_table(project_id, new_project_name: str) -> str | None:
    """Project was renamed: rename its user table to match. Returns the table name."""
    pid = int(project_id)
    current = await ensure_table(pid)
    slug = _slug(new_project_name)
    if not slug:
        return current
    if current in (f"{slug}_user", f"{slug}_{pid}_user"):
        return current          # already matches the new name
    new = await _pick_name(pid, new_project_name)
    if new == current:
        return current
    await execute(f'ALTER TABLE {_q(current)} RENAME TO "{new}"')
    await execute(f"UPDATE {_REGISTRY} SET table_name = $2 WHERE project_id = $1", pid, new)
    return new


async def drop_table(project_id) -> None:
    pid = int(project_id)
    name = await table_name_of(pid)
    if name:
        await execute(f"DROP TABLE IF EXISTS {_q(name)}")
        await execute(f"DELETE FROM {_REGISTRY} WHERE project_id = $1", pid)


async def add_user(project_id, user_id, role_ids: list[str] | None = None,
                   added_by: str | None = None) -> None:
    """Put a user in the project's table and link them to RBAC, atomically.

    role_ids=None  -> keep whatever project roles the user already has
    role_ids=[...] -> replace the user's roles inside this project
    """
    table = _q(await ensure_table(project_id))
    pid, uid = int(project_id), int(user_id)
    pool = await ensure_pool()
    async with pool.acquire() as conn:
        async with conn.transaction():
            await conn.execute(
                f"INSERT INTO {table} (user_id, added_by) VALUES ($1, $2) "
                f"ON CONFLICT (user_id) DO NOTHING",
                uid, added_by,
            )
            await conn.execute(
                "INSERT INTO idam.user_project (user_id, project_id) VALUES ($1, $2) "
                "ON CONFLICT DO NOTHING",
                uid, pid,
            )
            if role_ids is not None:
                await _replace_roles(conn, uid, pid, role_ids)


async def set_roles(project_id, user_id, role_ids: list[str]) -> None:
    uid, pid = int(user_id), int(project_id)
    pool = await ensure_pool()
    async with pool.acquire() as conn:
        async with conn.transaction():
            await _replace_roles(conn, uid, pid, role_ids)


async def _replace_roles(conn, uid: int, pid: int, role_ids: list[str]) -> None:
    await conn.execute(
        "DELETE FROM rbac_user_roles WHERE user_id = $1 AND project_id = $2", uid, pid,
    )
    if role_ids:
        await conn.executemany(
            "INSERT INTO rbac_user_roles (user_id, role_id, project_id) VALUES ($1, $2, $3) "
            "ON CONFLICT DO NOTHING",
            [(uid, rid, pid) for rid in role_ids],
        )


async def remove_user(project_id, user_id) -> bool:
    """Take a user out of the project: table row, membership and project roles."""
    table = _q(await ensure_table(project_id))
    uid, pid = int(user_id), int(project_id)
    pool = await ensure_pool()
    async with pool.acquire() as conn:
        async with conn.transaction():
            res = await conn.execute(f"DELETE FROM {table} WHERE user_id = $1", uid)
            await conn.execute(
                "DELETE FROM idam.user_project WHERE user_id = $1 AND project_id = $2", uid, pid,
            )
            await conn.execute(
                "DELETE FROM rbac_user_roles WHERE user_id = $1 AND project_id = $2", uid, pid,
            )
    return not res.endswith(" 0")


async def is_in_project(project_id, user_id) -> bool:
    table = _q(await ensure_table(project_id))
    row = await fetchrow(f"SELECT 1 FROM {table} WHERE user_id = $1", int(user_id))
    return row is not None


async def list_users(project_id) -> list[dict]:
    """Rows of the project's user table + user details + their roles in this project."""
    name = await ensure_table(project_id)
    pid = int(project_id)
    rows = await fetch(
        f"""
        SELECT pu.user_id, pu.added_by, pu.created_at,
               COALESCE(u.user_name, u.username) AS user_name, u.email, u.is_active
        FROM {_q(name)} pu
        JOIN idam."user" u ON u.id = pu.user_id
        ORDER BY LOWER(COALESCE(u.user_name, u.username))
        """
    )
    role_rows = await fetch(
        "SELECT ur.user_id, r.id, r.name FROM rbac_user_roles ur "
        "JOIN rbac_roles r ON r.id = ur.role_id WHERE ur.project_id = $1 ORDER BY r.name",
        pid,
    )
    roles_by_user: dict[str, list] = {}
    for rr in role_rows:
        roles_by_user.setdefault(str(rr["user_id"]), []).append({"id": rr["id"], "name": rr["name"]})
    return [
        {
            "user_id": str(r["user_id"]),
            "user_name": r["user_name"],
            "email": r["email"],
            "is_active": bool(r["is_active"]),
            "added_by": r["added_by"],
            "created_at": r["created_at"].isoformat() if r["created_at"] else None,
            "roles": roles_by_user.get(str(r["user_id"]), []),
        }
        for r in rows
    ]