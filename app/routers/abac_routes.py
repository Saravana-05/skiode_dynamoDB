"""
Domain ABAC API — attribute/role based access rules per domain model.

  GET    /abac/domains/{domain_name}   → rules of one domain
  PUT    /abac/domains/{domain_name}   → replace the domain's whole rule list
  DELETE /abac/domains/{domain_name}   → remove all rules of the domain

Reading needs a logged-in user. Changing rules needs an admin, or the
"domain_model" edit permission (same as designing domain models).
"""
from fastapi import APIRouter, Depends, HTTPException, Request
from pydantic import BaseModel

from ..dependencies.auth_dependency import get_current_user
from ..dependencies.rbac_dependency import require_permission
from ..services import abac_service as svc
from ..utils.decorators import handle_errors

router = APIRouter(prefix="/abac", tags=["ABAC"])
can_design = [Depends(require_permission("edit", "domain_model"))]


class RuleIn(BaseModel):
    id: str | None = None            # ignored — ids are generated by the database
    name: str
    effect: str                      # "allow" | "deny"
    roles: list[str] = []            # empty = any role
    actions: list[str] = []          # read / create / update / delete
    conditions: list[dict] = []      # row/user conditions, all must match (AND)


class SaveRulesRequest(BaseModel):
    rules: list[RuleIn] = []
    project_id: str | None = None
    module_id: str | None = None


def _raise_if_error(result: dict) -> dict:
    if result.get("status") == "error":
        raise HTTPException(status_code=result.get("code", 400), detail=result.get("message"))
    return result


@router.get("/domains/{domain_name}", summary="Get the ABAC rules of a domain model")
@handle_errors
async def get_domain_rules(domain_name: str, request: Request, current_user: dict = Depends(get_current_user)):
    return await svc.get_rules(domain_name)


@router.put("/domains/{domain_name}", dependencies=can_design, summary="Replace the ABAC rules of a domain model")
@handle_errors
async def save_domain_rules(domain_name: str, body: SaveRulesRequest, request: Request):
    return _raise_if_error(await svc.save_rules(domain_name, body.model_dump()))


@router.delete("/domains/{domain_name}", dependencies=can_design, summary="Delete all ABAC rules of a domain model")
@handle_errors
async def delete_domain_rules(domain_name: str, request: Request):
    return await svc.delete_rules(domain_name)